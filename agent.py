
import os
import json

from dotenv import load_dotenv
from google import genai
from google.genai import types

from utils.tools import (
    get_policy_details,
    make_claim_decision
)

from utils.document_processor import process_multiple_pdfs
from utils.document_validator import validate_documents


# ==========================================
# INITIALIZATION
# ==========================================

load_dotenv()

API_KEY = os.getenv("GEMINI_API_KEY")

if not API_KEY:
    raise ValueError("Gemini API key not found in .env file")

client = genai.Client(api_key=API_KEY)

MODEL = "gemini-3.5-flash-lite"


# ==========================================
# PYTHON FALLBACK REPORT
# ==========================================

def generate_fallback_report(
    policy_id,
    treatment,
    claim_amount,
    treatment_date,
    detected_documents,
    bill_details,
    document_errors,
    document_validation,
    decision,
    final_recommendation
):

    report = f"""
# INSUREASSIST - CLAIM ASSESSMENT REPORT

## 1. Claim Information

- Policy ID: {policy_id}
- Treatment: {treatment}
- Claim Amount: ₹{claim_amount:,.2f}
- Treatment Date: {treatment_date}

## 2. Uploaded Documents

"""

    if detected_documents:
        for document in detected_documents:
            report += f"- {document.title()}\n"
    else:
        report += "No documents were identified.\n"

    report += """
## 3. Extracted Hospital Bill Details

"""

    if bill_details:

        for key, value in bill_details.items():

            formatted_key = key.replace("_", " ").title()

            if isinstance(value, (int, float)):
                value = f"₹{value:,.2f}"

            report += f"- **{formatted_key}:** {value}\n"

    else:
        report += "Hospital bill details were not available.\n"

    report += "\n## 4. Document Processing Errors\n\n"

    if document_errors:
        for error in document_errors:
            report += f"- {error}\n"
    else:
        report += "No document processing errors reported.\n"

    report += "\n## 5. Document Validation\n\n"

    if document_validation:
        report += (
            "```json\n"
            + json.dumps(
                document_validation,
                indent=4,
                default=str
            )
            + "\n```\n"
        )
    else:
        report += "Document validation was not performed.\n"

    report += "\n## 6. Policy Eligibility Checks\n\n"

    report += (
        "```json\n"
        + json.dumps(
            decision,
            indent=4,
            default=str
        )
        + "\n```\n"
    )

    report += f"""
## 7. Final Assessment Recommendation

**{final_recommendation}**

## 8. Disclaimer

This report is generated by InsureAssist using automated
document processing and Python-based policy validation.

It is a preliminary recommendation only.
Final insurance claim decisions require human review.
"""

    return report


# ==========================================
# INSUREASSIST AI AGENT
# ==========================================

def assess_claim(claim_details, pdf_paths=None):

    # --------------------------------------
    # STEP 1: Extract claim details using Gemini
    # --------------------------------------

    extraction_prompt = f"""
    Extract the following information from this insurance claim.

    Return ONLY valid JSON with these exact keys:

    policy_id
    treatment
    claim_amount
    treatment_date
    submitted_documents

    claim_amount must be a number.
    submitted_documents must be a list of strings.

    If any information is missing, use null.

    Claim details:
    {claim_details}
    """

    extraction_response = client.models.generate_content(
        model=MODEL,
        contents=extraction_prompt,
        config=types.GenerateContentConfig(
            temperature=0
        )
    )

    try:

        extracted_data = json.loads(
            extraction_response.text.strip()
            .replace("```json", "")
            .replace("```", "")
            .strip()
        )

    except (json.JSONDecodeError, AttributeError):

        return (
            "Unable to extract claim information. "
            "Manual Review required."
        )

    required_fields = [
        "policy_id",
        "treatment",
        "claim_amount",
        "treatment_date",
        "submitted_documents"
    ]

    for field in required_fields:

        if extracted_data.get(field) is None:

            return (
                f"Missing claim information: {field}. "
                "Manual Review required."
            )

    try:

        claim_amount = float(extracted_data["claim_amount"])

        if claim_amount < 0:
            return "Invalid claim amount. Manual Review required."

    except (ValueError, TypeError):

        return "Invalid claim amount. Manual Review required."

    if not isinstance(extracted_data["submitted_documents"], list):

        return "Invalid document information. Manual Review required."

    policy_id = extracted_data["policy_id"]
    treatment = extracted_data["treatment"]
    treatment_date = extracted_data["treatment_date"]


    # --------------------------------------
    # STEP 2: Process uploaded PDF documents
    # --------------------------------------

    detected_documents = []
    bill_details = None
    document_errors = []

    if pdf_paths:

        processing_response = process_multiple_pdfs(pdf_paths)

        if not isinstance(processing_response, dict):

            document_errors.append(
                "Invalid response from PDF processor."
            )

        elif not processing_response.get("success", False):

            document_errors.append(
                processing_response.get(
                    "error",
                    "PDF processing failed."
                )
            )

        else:

            document_results = processing_response.get(
                "results", []
            )

            if not isinstance(document_results, list):

                document_errors.append(
                    "Invalid PDF results format."
                )

                document_results = []

            for pdf_result in document_results:

                if not isinstance(pdf_result, dict):

                    document_errors.append(
                        "Invalid individual PDF processing result."
                    )

                    continue

                if not pdf_result.get("success", False):

                    document_errors.append(
                        pdf_result.get(
                            "error",
                            "PDF processing failed."
                        )
                    )

                    continue

                for document in pdf_result.get(
                    "detected_documents", []
                ):

                    if not isinstance(document, dict):
                        continue

                    document_type = document.get(
                        "document_type"
                    )

                    if (
                        document_type
                        and document_type not in detected_documents
                    ):

                        detected_documents.append(document_type)

                    if (
                        document_type == "hospital bill"
                        and bill_details is None
                    ):

                        bill_details = pdf_result.get(
                            "bill_details"
                        )

        submitted_documents = detected_documents

    else:

        submitted_documents = extracted_data[
            "submitted_documents"
        ]


    # --------------------------------------
    # STEP 3: Get policyholder information
    # --------------------------------------

    policy = get_policy_details(policy_id)

    document_validation = None

    if policy and bill_details:

        document_validation = validate_documents(
            policyholder_name=policy["holder_name"],
            bill_details=bill_details,
            claim_amount=claim_amount,
            treatment_date=treatment_date
        )


    # --------------------------------------
    # STEP 4: Run Python claim decision engine
    # --------------------------------------

    decision = make_claim_decision(
        policy_id=policy_id,
        treatment=treatment,
        claim_amount=claim_amount,
        treatment_date=treatment_date,
        submitted_documents=submitted_documents
    )


    # --------------------------------------
    # STEP 5: Combine verification results
    # --------------------------------------

    base_classification = decision.get(
        "classification",
        "Manual Review"
    )

    final_recommendation = base_classification

    if base_classification != "Ineligible":

        if pdf_paths and not bill_details:

            final_recommendation = "Manual Review"

        elif document_errors:

            final_recommendation = "Manual Review"

        elif (
            document_validation
            and document_validation.get("overall_status") != "PASSED"
        ):

            final_recommendation = "Manual Review"


    complete_assessment = {

        "claim_information": {
            "policy_id": policy_id,
            "treatment": treatment,
            "claim_amount": claim_amount,
            "treatment_date": treatment_date
        },

        "detected_documents": detected_documents,

        "extracted_bill_details": bill_details,

        "document_processing_errors": document_errors,

        "document_validation": document_validation,

        "policy_decision": decision,

        "final_recommendation": final_recommendation
    }


    # --------------------------------------
    # STEP 6: Generate report using Gemini
    # --------------------------------------

    explanation_prompt = f"""
    You are InsureAssist, an intelligent insurance
    claim processing assistant.

    Explain the following complete claim assessment
    in a professional and understandable report.

    IMPORTANT RULES:

    1. Python decision engine is authoritative
       for policy eligibility.

    2. Python document validator is authoritative
       for document verification.

    3. Do not change or override either result.

    4. The final_recommendation field is authoritative.

    5. Explain identity mismatches and amount
       or date mismatches clearly.

    6. Mention missing documents.

    7. Never invent policy or document information.

    8. This is a recommendation for a human reviewer,
       not an actual insurance claim approval.

    Complete Python assessment:

    {json.dumps(complete_assessment, indent=4, default=str)}

    Generate a structured report containing:

    - Claim and policy information
    - Uploaded documents
    - Extracted hospital bill details
    - Document validation results
    - Policy eligibility checks
    - Missing documents
    - Final assessment recommendation
    - Reasons and disclaimer
    """

    # Try Gemini report generation

    try:

        explanation_response = client.models.generate_content(
            model=MODEL,
            contents=explanation_prompt,
            config=types.GenerateContentConfig(
                temperature=0.2
            )
        )

        if explanation_response.text:

            return explanation_response.text

    except Exception as error:

        print(
            "\nGemini report generation failed:",
            error
        )

        print(
            "Using Python fallback report instead."
        )


    # --------------------------------------
    # STEP 7: Python fallback report
    # --------------------------------------

    return generate_fallback_report(
        policy_id=policy_id,
        treatment=treatment,
        claim_amount=claim_amount,
        treatment_date=treatment_date,
        detected_documents=detected_documents,
        bill_details=bill_details,
        document_errors=document_errors,
        document_validation=document_validation,
        decision=decision,
        final_recommendation=final_recommendation
    )


